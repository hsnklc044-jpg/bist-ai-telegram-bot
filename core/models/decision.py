"""
QuantBIST Framework
Decision Model
"""

from __future__ import annotations

from dataclasses import dataclass
from datetime import datetime
from enum import Enum


# =====================================================
# ACTION
# =====================================================

class DecisionAction(Enum):
    """
    Final portfolio decision.
    """

    BUY = "BUY"

    HOLD = "HOLD"

    SELL = "SELL"

    REBALANCE = "REBALANCE"

    REDUCE_RISK = "REDUCE_RISK"


# =====================================================
# RISK
# =====================================================

class DecisionRisk(Enum):
    """
    Decision risk level.
    """

    LOW = "LOW"

    MEDIUM = "MEDIUM"

    HIGH = "HIGH"

    CRITICAL = "CRITICAL"


# =====================================================
# MARKET
# =====================================================

class MarketBias(Enum):
    """
    Overall market bias.
    """

    BULLISH = "BULLISH"

    NEUTRAL = "NEUTRAL"

    BEARISH = "BEARISH"


# =====================================================
# DECISION
# =====================================================

@dataclass(slots=True)
class Decision:
    """
    Final investment decision generated by
    the Decision Engine.

    Shared across:

    - Dashboard
    - Recommendation Engine
    - Morning Report
    - Telegram Bot
    """

    action: DecisionAction

    confidence: int

    score: int

    risk: DecisionRisk

    market_bias: MarketBias

    reason: str

    timestamp: datetime